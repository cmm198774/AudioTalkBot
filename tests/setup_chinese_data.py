# 重复追加时给用户消息加的连接词，避免完全重复显得生硬
_REPEAT_PREFIXES = ["对了，", "说起来，", "还想问你，", "另外，"]


# ==========================================
# 计算会话当前字符数
# ==========================================
def count_chars(session: dict) -> int:
    """
    统计会话对话记录的总字符数。
    Args:
        session: 会话记录 (dict)
    Returns:
        int: 总字符数
    """
    return sum(len(i.get("text", "")) for i in session["transcript"])


# ==========================================
# 主流程：建会话 → 填核心对话 → 循环补到目标字符数
# ==========================================
def main():
    """
    创建中文测试会话并预填对话到接近阈值。
    """
    try:
        auth.register(USERNAME, PASSWORD)
        print(f"Created user: {USERNAME}")
    except Exception:
        print("User already exists")

    session = storage.create_session(USERNAME, PERSONA, "audio_text")
    sid = session["id"]
    print(f"Created session: {sid}")

    for role, text in CORE_MESSAGES:
        storage.append_transcript(USERNAME, sid, role, text)

    # 循环追加扩展话题，直到达到目标字符数
    round_idx = 0
    while count_chars(storage.get_session(USERNAME, sid)) < TARGET_CHARS:
        for role, text in EXTRA_MESSAGES:
            if count_chars(storage.get_session(USERNAME, sid)) >= TARGET_CHARS:
                break
            if role == "user" and round_idx > 0:
                text = _REPEAT_PREFIXES[round_idx % len(_REPEAT_PREFIXES)] + text
            storage.append_transcript(USERNAME, sid, role, text)
        round_idx += 1
        if round_idx > 10:
            print("WARN: exceeded 10 rounds, stopping")
            break

    full = storage.get_session(USERNAME, sid)
    chars = count_chars(full)
    print(f"Session: {len(full['transcript'])} items, {chars} chars")
    print(f"Threshold: 12800 chars, gap: {12800 - chars}")
    print("")
    print("测试步骤:")
    print("  1. 登录 testuser/test123，选择本会话，开始对话")
    print("  2. 先问'我的猫叫什么名字'验证恢复记忆（应答: 豆豆）")
    print("  3. 再聊 1-2 轮触发自动压缩（注意 toast 提示）")
    print("  4. 压缩后再次验证关键事实:")
    print("     猫名/年龄 -> 豆豆，三岁")
    print("     旅行计划 -> 十月成都，大熊猫+火锅")
    print("     过敏 -> 海鲜，尤其是虾")
    print("     妈妈生日礼物 -> 下月15号，酒红色羊绒围巾")
    print("     乐器 -> 吉他，《晴天》")
    print("     三体角色 -> 章北海")
    print("     运动 -> 每周三羽毛球")


if __name__ == "__main__":
    main()
